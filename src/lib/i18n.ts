export type TranslationKey = keyof typeof es;

const dictionaries = { en, es } as const;

function interpolate(text: string, values?: TranslationValues) {
  if (!values) return text;
  return Object.entries(values).reduce((result, [key, value]) => result.replaceAll(`{${key}}`, String(value)), text);
}

export function createTranslator(language: FiscalixLanguage | undefined = "es") {
  const dictionary = dictionaries[language === "en" ? "en" : "es"];

  return (key: TranslationKey, values?: TranslationValues) => interpolate(dictionary[key] ?? es[key] ?? key, values);
}

export function resultCount(count: number, language: FiscalixLanguage | undefined = "es") {
  return createTranslator(language)(count === 1 ? "common.result" : "common.results", { count });
}
